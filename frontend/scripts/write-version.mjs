// Writes the frontend version (frontend/package.json, managed by bump_version.py) into a
// git-ignored TypeScript file read by the footer. Run before build, test, serve and lint.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const target = new URL(
  '../projects/web/src/app/core/version/frontend-version.generated.ts',
  import.meta.url,
);

writeFileSync(
  target,
  `// Generated by scripts/write-version.mjs from package.json: do not edit.\n` +
    `export const FRONTEND_VERSION = '${version}';\n`,
);
console.log(`Frontend version ${version} written`);
